"""Export the texts and settings of the PsychoPy version (study1_task.py)
to config.js for the web version, so both use the same wording.

    python tools/export_config.py ../Study1_PsychoPy/study1_task.py config.js
"""
import ast
import json
import sys

NAMES = ['TEAMS', 'QUALITIES', 'CONDITIONS', 'BOXES', 'N_BOXES', 'BOX_DISPLAY', 'N_STICKERS',
         'PRACTICE_MIDDLE', 'PRACTICE_SKIP_AFTER', 'BUBBLE_IN_TEST', 'MIDDLE_SNAP',
         'CHECK_FADED_OPACITY', 'SOLUTION_MAJORITY', 'UNCHOSEN_OPACITY', 'ANIMAL_COLORS',
         'DUTCH', 'TEXT', 'EXP_COLOR', 'EXP_BUTTON_COLOR', 'SELECTED_COLOR', 'SHOW_HELP',
         'EXP_TEXT', 'COLOR_NAMES', 'NEUTER_NL', 'COLOR_ADJ_NL', 'TEAM_NAMES', 'PLURALS',
         'MAX_CHECKS', 'CHECK_FIELDS', 'BOXES_OPENED', 'NUMBER_WORDS', 'MEMBER_WORDS',
         'REALLY', 'LATIN', 'ORDER_NAMES', 'N_LISTS']

source, target = sys.argv[1], sys.argv[2]
tree = ast.parse(open(source, encoding='utf-8').read())
cfg = {}
for node in tree.body:
    if (isinstance(node, ast.Assign) and len(node.targets) == 1
            and isinstance(node.targets[0], ast.Name) and node.targets[0].id in NAMES):
        value = ast.literal_eval(node.value)
        cfg[node.targets[0].id] = sorted(value) if isinstance(value, set) else value
missing = set(NAMES) - set(cfg)
assert not missing, f'not found in {source}: {missing}'
cfg['BOX_ORDER'] = list(cfg['BOXES'])
cfg['AGES'] = [str(a) for a in range(3, 11)]
with open(target, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/export_config.py from the PsychoPy version '
            '(study1_task.py) - same texts and settings.\n')
    f.write('const CFG = ' + json.dumps(cfg, ensure_ascii=False, indent=1) + ';\n')
print(f'{len(cfg)} settings written to {target}')
